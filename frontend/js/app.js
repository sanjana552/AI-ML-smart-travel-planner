const form = document.getElementById("trip-form");
const results = document.getElementById("results");
const statusEl = document.getElementById("status");
const submitButton = document.getElementById("submit-button");

const API_URL = "http://127.0.0.1:5000/api/itinerary";

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  })[char]);
}

function money(value) {
  const amount = Number(value);
  if (!Number.isFinite(amount)) return "Not available";
  return "₹" + amount.toLocaleString("en-IN", {
    maximumFractionDigits: 0
  });
}

function readable(value) {
  if (value === null || value === undefined || value === "") {
    return "Not available";
  }

  if (Array.isArray(value)) {
    return value.map(readable).join(", ");
  }

  if (typeof value === "object") {
    return Object.entries(value)
      .map(([key, val]) => `${key.replace(/_/g, " ")}: ${readable(val)}`)
      .join(" · ");
  }

  return String(value);
}

function getSourceInfo(source) {
  const normalised = String(source || "").toLowerCase();

  if (normalised.includes("ai-enriched") || normalised.includes("enriched")) {
    return {
      title: "Dataset Recommendation (AI-Enriched)",
      subtitle: "Dataset itinerary framework enriched with verified local attractions via Groq AI",
      icon: "🗂️",
      className: "source-dataset"
    };
  }

  if (normalised.includes("ai")) {
    return {
      title: "Generative AI",
      subtitle: "Custom itinerary generated by Groq AI",
      icon: "✦",
      className: "source-ai"
    };
  }

  return {
    title: "Dataset Recommendation",
    subtitle: "Curated itinerary from Triip travel dataset",
    icon: "🗂️",
    className: "source-dataset"
  };
}

function renderSource(source) {
  const info = getSourceInfo(source);

  return `
    <div class="source-panel ${info.className}">
      <span class="source-icon">${info.icon}</span>
      <div>
        <strong>Recommendation Source: ${escapeHtml(info.title)}</strong>
        <small>${escapeHtml(info.subtitle)}</small>
      </div>
    </div>
  `;
}

function renderStops(stops) {
  if (!Array.isArray(stops) || stops.length === 0) {
    return `<p class="stop-activity">No detailed activities were provided.</p>`;
  }

  return `
    <div class="stops-list">
      ${stops.map((stop, index) => {
        if (typeof stop !== "object" || stop === null) {
          return `
            <div class="stop-card">
              <div class="stop-activity">${escapeHtml(stop)}</div>
            </div>
          `;
        }

        const place = stop.place || stop.name || stop.attraction || "Activity";
        const time = stop.time || stop.period || "";
        const activity = stop.activity || stop.description || "";
        const cost = stop.estimated_cost;
        const travelDuration = stop.travel_duration;

        return `
          <article class="stop-card">
            <div class="stop-heading">
              <span class="stop-number">${index + 1}</span>
              <div class="stop-title">
                <h5>${escapeHtml(place)}</h5>
                ${time ? `<span class="stop-time">${escapeHtml(time)}</span>` : ""}
              </div>
            </div>

            ${activity ? `
              <p class="stop-activity">${escapeHtml(activity)}</p>
            ` : ""}

            <div class="stop-meta">
              ${cost !== undefined && cost !== null && cost !== ""
                ? `<span>Estimated cost: ${escapeHtml(money(cost))}</span>`
                : ""}
              ${travelDuration
                ? `<span>Travel time: ${escapeHtml(travelDuration)}</span>`
                : ""}
            </div>
          </article>
        `;
      }).join("")}
    </div>
  `;
}

function renderDailyPlan(dailyPlan) {
  if (!Array.isArray(dailyPlan)) {
    return `
      <div class="plan-text">${escapeHtml(readable(dailyPlan))}</div>
    `;
  }

  if (dailyPlan.length === 0) {
    return `<p>No day-wise details were provided.</p>`;
  }

  return `
    <div class="days-list">
      ${dailyPlan.map((day, index) => {
        if (typeof day !== "object" || day === null) {
          return `
            <article class="day-card">
              <div class="day-heading">
                <div>
                  <span class="day-label">DAY ${index + 1}</span>
                  <h4>${escapeHtml(day)}</h4>
                </div>
              </div>
            </article>
          `;
        }

        const dayNumber = day.day || index + 1;
        const title = day.title || `Day ${dayNumber} exploration`;
        const stops = day.stops || day.activities || [];
        const dayCost = day.estimated_day_cost;

        return `
          <article class="day-card">
            <div class="day-heading">
              <div>
                <span class="day-label">DAY ${escapeHtml(dayNumber)}</span>
                <h4>${escapeHtml(title)}</h4>
              </div>

              ${dayCost !== undefined && dayCost !== null
                ? `<span class="day-cost">${escapeHtml(money(dayCost))}</span>`
                : ""}
            </div>

            ${renderStops(stops)}
          </article>
        `;
      }).join("")}
    </div>
  `;
}

function renderBudget(budget) {
  if (!budget || typeof budget !== "object" || Array.isArray(budget)) {
    return "";
  }

  const total = budget.estimated_total ?? budget.total ?? 0;
  const perPerson = budget.per_person_cost;
  const travellers = budget.num_travellers;
  const status = budget.budget_status || "";
  const assumptions = budget.assumptions || "";
  const explanation = budget.budget_explanation || "";
  const disclaimer = budget.disclaimer || "AI-generated cost estimate in INR. Verify with live booking sites.";

  let statusClass = "status-within";
  let statusIcon = "✓";
  if (status.toLowerCase().includes("unrealistic")) {
    statusClass = "status-unrealistic";
    statusIcon = "✕";
  } else if (status.toLowerCase().includes("tight") || status.toLowerCase().includes("moderate")) {
    statusClass = "status-tight";
    statusIcon = "⚠️";
  }

  const categoryItems = [
    { label: "Accommodation (Stay)", value: budget.accommodation },
    { label: "Food & Dining", value: budget.food },
    { label: "Local Transport", value: budget.local_transport },
    { label: "Attraction Fees & Sightseeing", value: budget.attraction_fees },
    { label: "Miscellaneous & Buffer", value: budget.miscellaneous }
  ].filter(item => item.value !== undefined && item.value !== null);

  return `
    <section class="budget-section">
      <h4>ESTIMATED BUDGET BREAKDOWN (INR)</h4>

      <div class="budget-summary-card">
        <div class="budget-summary-left">
          <small>Total Estimated Cost</small>
          <span class="total-amount">${escapeHtml(money(total))}</span>
        </div>

        <div class="budget-summary-right">
          ${perPerson !== undefined && perPerson !== null ? `
            <span class="per-person-pill">
              👤 ${escapeHtml(money(perPerson))} / person ${travellers ? `(${escapeHtml(travellers)} travellers)` : ''}
            </span>
          ` : ""}

          ${status ? `
            <span class="budget-status-pill ${statusClass}">
              ${statusIcon} ${escapeHtml(status)}
            </span>
          ` : ""}
        </div>
      </div>

      <div class="budget-grid">
        ${categoryItems.map(item => `
          <div class="budget-item">
            <span>${escapeHtml(item.label)}</span>
            <strong>${escapeHtml(money(item.value))}</strong>
          </div>
        `).join("")}
      </div>

      ${assumptions || explanation ? `
        <div class="budget-notes-box">
          ${assumptions ? `<strong>Assumptions:</strong> ${escapeHtml(assumptions)}` : ''}
          ${explanation ? `<p style="margin-top: 6px;"><strong>Budget Realism:</strong> ${escapeHtml(explanation)}</p>` : ''}
        </div>
      ` : ""}

      <p class="small-note">
        ⓘ ${escapeHtml(disclaimer)}
      </p>
    </section>
  `;
}

function renderPlan(plan, index, responseSource) {
  const source = plan.source || responseSource || "Dataset Recommendation";
  const destination = plan.destination || "Suggested trip";
  const days = plan.duration_days || plan.days || "N/A";
  const budget = plan.budget_amount ?? plan.budget;
  const score = Number(plan.match_score);
  const isDataset = !String(source).toLowerCase().includes("ai");
  const hasScore = isDataset &&
    plan.match_score !== null &&
    plan.match_score !== undefined &&
    plan.match_score !== "" &&
    Number.isFinite(score);

  const budgetText = budget !== undefined && budget !== null
    ? money(budget)
    : "Not specified";

  return `
    <article class="trip-card">
      <div class="trip-card-head">
        <div>
          <h3>${index + 1}. ${escapeHtml(destination)}</h3>
          <div class="meta">
            <span class="tag">${escapeHtml(days)} days</span>
            <span class="tag">Target Budget: ${escapeHtml(budgetText)}</span>
          </div>
        </div>

        ${hasScore
          ? `<span class="score">Match score: ${(score * 100).toFixed(1)}%</span>`
          : ""}
      </div>

      <div class="trip-card-body">
        ${renderSource(source)}

        ${plan.notice ? `
          <div class="plan-notice-card">
            <strong>Plan Notice:</strong> ${escapeHtml(plan.notice)}
          </div>
        ` : ""}

        <h4>DAY-WISE ITINERARY</h4>
        ${renderDailyPlan(plan.daily_plan)}

        ${renderBudget(plan.budget_breakdown)}

        <p class="small-note">
          Estimated costs and activities are based on AI and travel dataset models and do not reflect real-time live availability. Please verify before travelling.
        </p>
      </div>
    </article>
  `;
}

form.addEventListener("submit", async event => {
  event.preventDefault();

  const formData = new FormData(form);
  const data = Object.fromEntries(formData.entries());

  data.destination = String(data.destination || "").trim();
  data.days = Number(data.days);
  data.budget = Number(data.budget);

  if (!data.destination) {
    alert("Please enter a destination.");
    return;
  }

  if (!Number.isInteger(data.days) || data.days < 1 || data.days > 30) {
    alert("Please enter a number of days between 1 and 30.");
    return;
  }

  if (!Number.isFinite(data.budget) || data.budget <= 0) {
    alert("Please enter a valid budget in rupees.");
    return;
  }

  submitButton.disabled = true;
  submitButton.innerHTML = "<span>Searching & Generating Itinerary...</span><span>⏳</span>";
  statusEl.textContent = "Processing...";
  results.innerHTML = `
    <div class="empty-state">
      <h3>Planning your journey to ${escapeHtml(data.destination)}...</h3>
      <p>Matching travel dataset recommendations and preparing AI budget estimates.</p>
    </div>
  `;

  try {
    const response = await fetch(API_URL, {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify(data)
    });

    const payload = await response.json().catch(() => ({}));

    if (!response.ok) {
      throw new Error(
        payload.details ||
        payload.error ||
        `Server returned status ${response.status}`
      );
    }

    const plans = Array.isArray(payload.recommendations)
      ? payload.recommendations
      : [];

    if (plans.length === 0) {
      throw new Error(
        payload.notice || "No itinerary was returned. Try again."
      );
    }

    const notice = payload.notice
      ? `<div class="alert">${escapeHtml(payload.notice)}</div>`
      : "";

    results.innerHTML = notice + plans
      .map((plan, index) => renderPlan(plan, index, payload.source))
      .join("");

    statusEl.textContent = `${plans.length} plan(s) ready (${payload.source})`;

  } catch (error) {
    console.error("Itinerary request failed:", error);
    statusEl.textContent = "Could not generate";

    results.innerHTML = `
      <div class="alert">
        <strong>Could not generate your itinerary.</strong>
        <p>${escapeHtml(error.message)}</p>
        <p>Check that the Flask backend is running at http://127.0.0.1:5000.</p>
      </div>
    `;
  } finally {
    submitButton.disabled = false;
    submitButton.innerHTML =
      "<span>Generate my itinerary</span><span class=\"button-arrow\">↗</span>";
  }
});
